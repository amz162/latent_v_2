def _safe_round(v, n=2):
    try:
        if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
            return 0.0
        return round(float(v), n)
    except Exception:
        return 0.0


def build_prediction(model_name: str, symbol: str, df: pd.DataFrame) -> Optional[dict]:
    """Build a per-stock prediction for the given (model, symbol).
    Returns None if the stock has insufficient bars.
    """
    n = len(df)
    if n < MIN_BARS:
        return None

    # Add features (for ATR + support cache)
    try:
        feat = add_features(df)
    except Exception:
        return None
    t = len(feat) - 1
    cp = float(feat.iloc[t]["close"])
    atr = float(feat.iloc[t]["atr_14"]) if feat.iloc[t]["atr_14"] > 0 else cp * 0.02
    if atr <= 0 or cp <= 0:
        return None

    # Per-stock signal (Ridge proxy for deep-learning models)
    use_ridge = model_name in DEEP_LEARNING
    sig, direction, confidence, prob_up = per_stock_signal(feat, use_ridge=use_ridge)

    # Common base fields
    base = {
        "signal": sig,
        "direction": direction,
        "confidence": int(max(0, min(100, confidence))),
        "currentPrice": _safe_round(cp),
        "entry": _safe_round(cp),
        "avgReturn": _safe_round((prob_up - 0.5) * 2, 4),
        "_proxy": True,
    }

    # ── Dispatch SL/TP rule by model group ──
    if model_name in MULTI_TIER or model_name in CL_TIER or model_name in DEEP_LEARNING:
        sl, tp1, tp2, tp3, r = compute_multi_sl_and_targets(cp, atr, sig if sig != "HOLD" else "BUY")
        base.update(sl=_safe_round(sl), tp1=_safe_round(tp1), tp2=_safe_round(tp2), tp3=_safe_round(tp3))
        if sig == "HOLD":
            base.update(sl=_safe_round(cp), tp1=_safe_round(cp), tp2=_safe_round(cp), tp3=_safe_round(cp))
        # deep-learning & CG-classifier models carry raw_prob
        if model_name in DEEP_LEARNING or model_name in CG_TIER or model_name in CL2_TIER or model_name in PI_TIER:
            base["raw_prob"] = round(float(prob_up), 4)

    elif model_name in CL2_TIER or model_name in PI_TIER:
        sc = StockSupportCache(feat)
        sup = sc.support_at(t)
        res = sc.resistance_at(t)
        if math.isnan(sup) or math.isnan(res):
            # Fallback to ATR rule if support detection fails
            sl, tp1, tp2, tp3, r = compute_multi_sl_and_targets(cp, atr, sig if sig != "HOLD" else "BUY")
        else:
            sl, tp1, tp2, tp3, r, skip = compute_cl2_sl_and_targets(
                cp, atr, sup, res, sig if sig != "HOLD" else "BUY"
            )
        base.update(sl=_safe_round(sl), tp1=_safe_round(tp1), tp2=_safe_round(tp2), tp3=_safe_round(tp3))
        base["raw_prob"] = round(float(prob_up), 4)
        if sig == "HOLD":
            base.update(sl=_safe_round(cp), tp1=_safe_round(cp), tp2=_safe_round(cp), tp3=_safe_round(cp))

    elif model_name in GM_TIER:
        sl, tp1, tp2, tp3, r = compute_gm_sl_and_targets(cp, atr, sig if sig != "HOLD" else "BUY")
        base.update(sl=_safe_round(sl), tp1=_safe_round(tp1), tp2=_safe_round(tp2), tp3=_safe_round(tp3))
        if sig == "HOLD":
            base.update(sl=_safe_round(cp), tp1=_safe_round(cp), tp2=_safe_round(cp), tp3=_safe_round(cp))
        # GM pillar score — just stash the prob as the pillar score
        pillar_score = (prob_up - 0.5) * 2  # ∈ [-1, +1]
        base["total_score"] = round(float(pillar_score), 3)
        base["pillars"] = {
            "tech_score": round(float(pillar_score), 3) if "Technical" in model_name else 0.0,
            "anno_score": round(float(pillar_score), 3) if "Announcements" in model_name else 0.0,
            "fund_score": round(float(pillar_score), 3) if "Fundamental" in model_name else 0.0,
            "macro_score": round(float(pillar_score), 3) if "Macro" in model_name else 0.0,
            "total_score": round(float(pillar_score), 3),
        }

    elif model_name in CG_TIER or model_name in X_TIER:
        sc = StockSupportCache(feat)
        sup = sc.support_at(t)
        res = sc.resistance_at(t)
        if math.isnan(sup) or math.isnan(res):
            sl, tp1, tp2, tp3, r = compute_multi_sl_and_targets(cp, atr, sig if sig != "HOLD" else "BUY")
        else:
            sl, tp1, tp2, tp3, r, skip = compute_cg_sl_and_targets(
                cp, atr, sup, res, sig if sig != "HOLD" else "BUY"
            )
        base.update(sl=_safe_round(sl), tp1=_safe_round(tp1), tp2=_safe_round(tp2), tp3=_safe_round(tp3))
        base["raw_prob"] = round(float(prob_up), 4)
        base["agreement"] = 1.0  # single-model proxy — full agreement
        base["exp_win_rate"] = round(float(prob_up), 4)
        if sig == "HOLD":
            base.update(sl=_safe_round(cp), tp1=_safe_round(cp), tp2=_safe_round(cp), tp3=_safe_round(cp))

    elif model_name in GIAN_TIER:
        sc = StockSupportCache(feat)
        sup = sc.support_at(t)
        res = sc.resistance_at(t)
        # Compute Gian/GANN/M levels
        if model_name == "Gian-Ensemble (GIAN)":
            levels = compute_gian_levels(cp)
            base["gian_levels"] = [float(x) for x in levels]
        elif model_name == "Gian-Extender (GIAN-EXT)":
            levels = compute_gann_levels(cp)
            base["gann_levels"] = [float(x) for x in levels]
        elif model_name == "M-Ensemble (M)":
            high_arr = feat["high"].astype(float).values
            low_arr = feat["low"].astype(float).values
            close_arr = feat["close"].astype(float).values
            atr_arr = feat["atr_14"].astype(float).values
            levels = compute_m_levels(high_arr, low_arr, close_arr, atr_arr, t)
            base["m_levels"] = [float(x) for x in levels]
        # SL/TP via CG rule (Gian/M all use CG-style 1R/2R/3R)
        if math.isnan(sup) or math.isnan(res):
            sl, tp1, tp2, tp3, r = compute_multi_sl_and_targets(cp, atr, sig if sig != "HOLD" else "BUY")
        else:
            sl, tp1, tp2, tp3, r, skip = compute_cg_sl_and_targets(
                cp, atr, sup, res, sig if sig != "HOLD" else "BUY"
            )
        base.update(sl=_safe_round(sl), tp1=_safe_round(tp1), tp2=_safe_round(tp2), tp3=_safe_round(tp3))
        if sig == "HOLD":
            base.update(sl=_safe_round(cp), tp1=_safe_round(cp), tp2=_safe_round(cp), tp3=_safe_round(cp))
        # Gian/M signals carry no avgReturn normally (set to 0 to match)
        base["avgReturn"] = 0.0

    else:
        # Fallback: multi-tier rule
        sl, tp1, tp2, tp3, r = compute_multi_sl_and_targets(cp, atr, sig if sig != "HOLD" else "BUY")
        base.update(sl=_safe_round(sl), tp1=_safe_round(tp1), tp2=_safe_round(tp2), tp3=_safe_round(tp3))
        if sig == "HOLD":
            base.update(sl=_safe_round(cp), tp1=_safe_round(cp), tp2=_safe_round(cp), tp3=_safe_round(cp))

    return base


