def compute_gann_levels(cp: float) -> List[float]:
    """Return the 10 nearest GANN grid levels around cp (matches existing shape)."""
    if cp <= 0:
        return [float(x) for x in GANN_LEVELS[:10]]
    arr = np.array(GANN_LEVELS)
    # find insertion point
    idx = int(np.searchsorted(arr, cp))
    lo = max(0, idx - 5)
    hi = min(len(arr), idx + 5)
    return [float(x) for x in arr[lo:hi]]


def compute_m_levels(
    high_arr: np.ndarray, low_arr: np.ndarray, close_arr: np.ndarray,
    atr_arr: np.ndarray, t: int, n_levels: int = 3
) -> List[float]:
    """Touch-cluster S/R — pick 3 nearest support + resistance clusters."""
    if t < 30:
        return []
    cp = float(close_arr[t])
    atr = float(atr_arr[t]) if atr_arr[t] > 0 else cp * 0.02
    if atr <= 0:
        atr = cp * 0.02
    cluster_radius = atr * 1.0
    lookback = min(t, 250)
    candidates: List[Tuple[float, str]] = []
    for i in range(t - lookback, t + 1):
        if i < 0:
            continue
        candidates.append((float(high_arr[i]), "R"))
        candidates.append((float(low_arr[i]), "S"))
    if not candidates:
        return []
    candidates.sort(key=lambda x: x[0])
    clusters = []
    cur_prices = [candidates[0][0]]
    cur_count = 1
    for i in range(1, len(candidates)):
        p, _ = candidates[i]
        if p - cur_prices[-1] <= cluster_radius:
            cur_prices.append(p)
            cur_count += 1
        else:
            clusters.append((float(np.mean(cur_prices)), cur_count))
            cur_prices = [p]
            cur_count = 1
    clusters.append((float(np.mean(cur_prices)), cur_count))
    # Sort by touch count desc, pick top 3 below + top 3 above cp
    clusters.sort(key=lambda x: -x[1])
    sup, res = [], []
    for c, _ in clusters:
        if c < cp and len(sup) < n_levels:
            sup.append(c)
        elif c > cp and len(res) < n_levels:
            res.append(c)
        if len(sup) >= n_levels and len(res) >= n_levels:
            break
    return [round(float(x), 2) for x in (sup + res)][:3]


# ────────────────────────────────────────────────────────────────────────────
# Per-stock signal generator (LightGBM on stock's own bars; technical fallback
# for <ML_MIN_BARS bars; Ridge proxy for deep-learning models)
# ────────────────────────────────────────────────────────────────────────────

def technical_fallback(df: pd.DataFrame) -> Tuple[str, float, float, float]:
    """EMA(20/50) + RSI(14) + ATR(14) technical signal.
    Returns (signal, direction, confidence, prob_up).
    Mirrors the technical fallback in src/app/api/ai-model-signals + train_all_ensembles_am.
    """
    closes = df["close"].astype(float).values
    if len(closes) < 5:
        return "HOLD", "LONG", 50, 0.5
    # EMA(20), EMA(50)
    s = pd.Series(closes)
    ema20 = float(s.ewm(span=20, adjust=False).mean().iloc[-1])
    ema50 = float(s.ewm(span=min(50, len(s)), adjust=False).mean().iloc[-1])
    # RSI(14) (simple)
    delta = np.diff(closes[-15:])
    if len(delta) > 0:
        gain = np.where(delta > 0, delta, 0).sum()
        loss = -np.where(delta < 0, delta, 0).sum()
        if loss == 0:
            rsi = 100.0
        elif gain == 0:
            rsi = 0.0
        else:
            rs = (gain / 14) / (loss / 14)
            rsi = 100 - 100 / (1 + rs)
    else:
        rsi = 50.0
    # Probability proxy from RSI (0=prob down=1, 100=prob up=1)
    prob_up = max(0.0, min(1.0, rsi / 100.0))
    if ema20 > ema50 or rsi < 30:
        return "BUY", "LONG", int(prob_up * 100), prob_up
    elif ema20 < ema50 or rsi > 70:
        return "SELL", "SHORT", int((1 - prob_up) * 100), prob_up
    else:
        return "HOLD", "LONG", int(max(prob_up, 1 - prob_up) * 100), prob_up


def per_stock_signal(df: pd.DataFrame, use_ridge: bool = False) -> Tuple[str, float, float, float]:
    """Train a quick per-stock classifier on the stock's own bars.
    Label = price up 3% in next 21 days (forward-max return).
    Returns (signal, direction, confidence, prob_up).
    For deep-learning models (use_ridge=True), use Ridge + mark _proxy.
    """
    n = len(df)
    if n < ML_MIN_BARS or not HAVE_SK:
        return technical_fallback(df)

    # Build features
    try:
        feat = add_features(df)
    except Exception:
        return technical_fallback(df)

    # Forward window label: did the price go up 3% within FORWARD_WINDOW bars?
    closes = feat["close"].astype(float).values
    # future_max[i] = max(closes[i+1:i+1+FORWARD_WINDOW])
    fw = FORWARD_WINDOW
    future_max = np.full(len(closes), np.nan)
    for i in range(len(closes) - fw):
        future_max[i] = closes[i + 1:i + 1 + fw].max()
    future_ret = (future_max - closes) / np.where(closes == 0, 1, closes)
    feat["_y"] = (future_ret >= UP_THRESHOLD).astype(int)
    feat = feat.dropna(subset=["_y"])
    # Need at least 30 labeled rows
    if len(feat) < 30 or feat["_y"].nunique() < 2:
        return technical_fallback(df)

    X = feat[FC].fillna(0).values.astype(np.float32)
    y = feat["_y"].values.astype(int)
    # Latest bar's features (the prediction target)
    latest = feat.iloc[-1][FC].fillna(0).values.astype(np.float32).reshape(1, -1)

    try:
        if use_ridge or not HAVE_LGB:
            # Ridge proxy for deep-learning models
            from sklearn.linear_model import LogisticRegression
            from sklearn.preprocessing import StandardScaler
            scaler = StandardScaler()
            Xs = scaler.fit_transform(X)
            m = LogisticRegression(C=0.5, max_iter=200, random_state=42)
            m.fit(Xs, y)
            prob_up = float(m.predict_proba(scaler.transform(latest))[0, 1])
        else:
            # LightGBM
            m = lgb.LGBMClassifier(
                n_estimators=80, max_depth=4, num_leaves=15,
                learning_rate=0.05, random_state=42, verbose=-1, n_jobs=-1,
            )
            m.fit(X, y)
            prob_up = float(m.predict_proba(latest)[0, 1])
    except Exception:
        return technical_fallback(df)

    if prob_up >= 0.55:
        return "BUY", "LONG", int(prob_up * 100), prob_up
    elif prob_up <= 0.45:
        return "SELL", "SHORT", int((1 - prob_up) * 100), prob_up
    else:
        return "HOLD", "LONG", int(max(prob_up, 1 - prob_up) * 100), prob_up


