def crsi(p: pd.Series, n: int = 14) -> pd.Series:
    d = p.diff()
    g = d.where(d > 0, 0.0)
    l = -d.where(d < 0, 0.0)
    ag = g.ewm(alpha=1 / n, min_periods=n).mean()
    al = l.ewm(alpha=1 / n, min_periods=n).mean()
    return (100 - 100 / (1 + ag / al.replace(0, np.nan))).fillna(50)


def cmacd(p: pd.Series) -> Tuple[pd.Series, pd.Series, pd.Series]:
    e12 = p.ewm(span=12, adjust=False).mean()
    e26 = p.ewm(span=26, adjust=False).mean()
    m = e12 - e26
    s = m.ewm(span=9, adjust=False).mean()
    return m, s, m - s


def cbb(p: pd.Series, w: int = 20) -> Tuple[pd.Series, pd.Series]:
    sma = p.rolling(w).mean()
    sd = p.rolling(w).std()
    bw = ((sma + 2 * sd - (sma - 2 * sd)) / sma).fillna(0)
    pb = ((p - (sma - 2 * sd)) / (4 * sd).replace(0, np.nan)).fillna(0.5)
    return bw, pb


def catr(h: pd.Series, l: pd.Series, c: pd.Series, n: int = 14) -> pd.Series:
    tr = pd.concat(
        [h - l, (h - c.shift()).abs(), (l - c.shift()).abs()], axis=1
    ).max(axis=1)
    return tr.rolling(n).mean().fillna(0)


def cobv(c: pd.Series, v: pd.Series) -> pd.Series:
    s = c.diff().apply(lambda x: 1 if x > 0 else (-1 if x < 0 else 0))
    return (s * v).cumsum()


