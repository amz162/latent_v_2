def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        v = float(o)
        return 0 if (math.isnan(v) or math.isinf(v)) else v
    if isinstance(o, float):
        if math.isnan(o) or math.isinf(o):
            return 0
        return o
    return str(o)


def atomic_save(multi: dict, path: Path = PRED_FILE):
    """Write to .tmp then os.rename to avoid corruption if interrupted."""
    tmp = path.with_suffix(".json.tmp")
    with open(tmp, "w") as f:
        json.dump(multi, f, indent=2, default=_json_default, allow_nan=False)
    os.replace(tmp, path)


