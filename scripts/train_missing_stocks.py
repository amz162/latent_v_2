# StockSupportCache — causal swing-low/high support/resistance
# (mirrors train_cl2_tier.StockSupportCache)
# ────────────────────────────────────────────────────────────────────────────

def _detect_swings(arr: np.ndarray, lookback: int = 3, is_low: bool = True) -> np.ndarray:
    n = len(arr)
    if n < 2 * lookback + 1:
        return np.array([], dtype=int)
    out = []
    for i in range(lookback, n - lookback):
        center = arr[i]
        left = arr[i - lookback:i]
        right = arr[i + 1:i + 1 + lookback]
        if is_low:
            if np.all(left > center) and np.all(right > center):
                out.append(i)
        else:
            if np.all(left < center) and np.all(right < center):
                out.append(i)
    return np.array(out, dtype=int)


class StockSupportCache:
    """Causal swing-low/high support/resistance lookup.

    A swing low at bar i is "confirmed" once bars i+1..i+3 are seen.
    At prediction time t, the latest confirmed swing low is from bar t-3.
    Falls back to rolling 20-day low if no swing low is confirmed yet.
    """

    def __init__(self, sd: pd.DataFrame, lookback: int = 3):
        self.lookback = lookback
        low = sd["low"].astype(float).values
        high = sd["high"].astype(float).values
        self.swl_idx = _detect_swings(low, lookback=lookback, is_low=True)
        self.swl_val = low[self.swl_idx] if len(self.swl_idx) > 0 else np.array([])
        self.swh_idx = _detect_swings(high, lookback=lookback, is_low=False)
        self.swh_val = high[self.swh_idx] if len(self.swh_idx) > 0 else np.array([])
        low_s = pd.Series(low)
        high_s = pd.Series(high)
        self.rolling_min_20 = low_s.rolling(20, min_periods=1).min().values
        self.rolling_max_20 = high_s.rolling(20, min_periods=1).max().values

    def support_at(self, t: int) -> float:
        if t < self.lookback + 1:
            return float("nan")
        cutoff = t - 1 - self.lookback
        swing_support = float("nan")
        if len(self.swl_idx) > 0:
            mask = self.swl_idx <= cutoff
            valid_val = self.swl_val[mask]
            if len(valid_val) > 0:
                swing_support = float(valid_val[-1])
        twenty_low = float(self.rolling_min_20[t - 1]) if t >= 1 else float(self.rolling_min_20[0])
        candidates = [v for v in [swing_support, twenty_low] if not (v != v) and v > 0]
        return max(candidates) if candidates else float("nan")

    def resistance_at(self, t: int) -> float:
        if t < self.lookback + 1:
            return float("nan")
        cutoff = t - 1 - self.lookback
        swing_resistance = float("nan")
        if len(self.swh_idx) > 0:
            mask = self.swh_idx <= cutoff
            valid_val = self.swh_val[mask]
            if len(valid_val) > 0:
                swing_resistance = float(valid_val[-1])
        twenty_high = float(self.rolling_max_20[t - 1]) if t >= 1 else float(self.rolling_max_20[0])
        candidates = [v for v in [swing_resistance, twenty_high] if not (v != v) and v > 0]
        return min(candidates) if candidates else float("nan")


# ────────────────────────────────────────────────────────────────────────────
# SL/TP rules per model group
# ────────────────────────────────────────────────────────────────────────────

ATR_STOP_MULT = 0.8
SUPPORT_BUFFER_MULT = 0.15
MIN_SL_MULT = 0.5


def compute_cl2_sl_and_targets(
    cp: float, atr: float, support: float, resistance: float, direction: str
) -> Tuple[float, float, float, float, float, bool]:
    """CL-2/PI rule: support−0.15×ATR or entry∓0.8×ATR (closer, min 0.5×ATR).
    TP1/2/3 = 1.5R/3R/5R.
    Returns (sl, tp1, tp2, tp3, r, skip).
    """
    nan = math.isnan(support) or math.isnan(resistance)
    sup = support if not math.isnan(support) else cp - ATR_STOP_MULT * atr
    res = resistance if not math.isnan(resistance) else cp + ATR_STOP_MULT * atr
    if direction == "BUY":
        support_stop = sup - SUPPORT_BUFFER_MULT * atr
        atr_stop = cp - ATR_STOP_MULT * atr
        sl = max(support_stop, atr_stop)
        min_sl = cp - MIN_SL_MULT * atr
        if (cp - sl) < MIN_SL_MULT * atr:
            sl = min_sl
        r = cp - sl
        tp1 = cp + 1.5 * r
        tp2 = cp + 3.0 * r
        tp3 = cp + 5.0 * r
        skip = (not nan) and (res - cp) < 1.0 * r
    else:
        resistance_stop = res + SUPPORT_BUFFER_MULT * atr
        atr_stop = cp + ATR_STOP_MULT * atr
        sl = min(resistance_stop, atr_stop)
        max_sl = cp + MIN_SL_MULT * atr
        if (sl - cp) < MIN_SL_MULT * atr:
            sl = max_sl
        r = sl - cp
        tp1 = cp - 1.5 * r
        tp2 = cp - 3.0 * r
        tp3 = cp - 5.0 * r
        skip = (not nan) and (cp - sup) < 1.0 * r
    return float(sl), float(tp1), float(tp2), float(tp3), float(r), bool(skip)


def compute_cg_sl_and_targets(
    cp: float, atr: float, support: float, resistance: float, direction: str
) -> Tuple[float, float, float, float, float, bool]:
    """CG/X/Gian/M rule: same SL logic as CL-2 but TP1/2/3 = 1R/2R/3R."""
    sl, _tp1, _tp2, _tp3, r, skip = compute_cl2_sl_and_targets(
        cp, atr, support, resistance, direction
    )
    if direction == "BUY":
        tp1 = cp + 1.0 * r
        tp2 = cp + 2.0 * r
        tp3 = cp + 3.0 * r
    else:
        tp1 = cp - 1.0 * r
        tp2 = cp - 2.0 * r
        tp3 = cp - 3.0 * r
    return float(sl), float(tp1), float(tp2), float(tp3), float(r), bool(skip)


def compute_multi_sl_and_targets(
    cp: float, atr: float, direction: str
) -> Tuple[float, float, float, float, float]:
    """Multi-tier rule: SL = entry∓1.5×ATR, TP1/2/3 = entry±1/2/3×ATR."""
    if direction == "BUY":
        sl = cp - 1.5 * atr
        tp1 = cp + 1.0 * atr
        tp2 = cp + 2.0 * atr
        tp3 = cp + 3.0 * atr
    else:
        sl = cp + 1.5 * atr
        tp1 = cp - 1.0 * atr
        tp2 = cp - 2.0 * atr
        tp3 = cp - 3.0 * atr
    r = abs(cp - sl)
    return float(sl), float(tp1), float(tp2), float(tp3), float(r)


def compute_gm_sl_and_targets(
    cp: float, atr: float, direction: str
) -> Tuple[float, float, float, float, float]:
    """GM rule: SL = entry∓1.5×ATR, TP1/2/3 = entry±1.5/3/4.5×ATR."""
    if direction == "BUY":
        sl = cp - 1.5 * atr
        tp1 = cp + 1.5 * atr
        tp2 = cp + 3.0 * atr
        tp3 = cp + 4.5 * atr
    else:
        sl = cp + 1.5 * atr
        tp1 = cp - 1.5 * atr
        tp2 = cp - 3.0 * atr
        tp3 = cp - 4.5 * atr
    r = abs(cp - sl)
    return float(sl), float(tp1), float(tp2), float(tp3), float(r)


# ────────────────────────────────────────────────────────────────────────────
# Gian / GANN / M-Ensemble level computation (rule-based)
# ────────────────────────────────────────────────────────────────────────────

def make_odd(n: int) -> int:
    n = int(n)
    if n % 2 == 0:
        n += 1
    return n


def compute_gian_levels(cp: float) -> List[float]:
    """Square-root S/R: X=floor(sqrt(P)) (made odd); levels = X²,(X-1)²,(X+1)²,..."""
    if cp is None or (isinstance(cp, float) and (math.isnan(cp) or math.isinf(cp))) or cp <= 0:
        cp = 1.0
    x = int(math.isqrt(int(cp)))
    if x % 2 == 0:
        x += 1
    s1 = make_odd(x * x)
    r1 = make_odd((x + 1) * (x + 1))
    s2 = make_odd((x - 1) * (x - 1))
    r2 = make_odd((x + 2) * (x + 2))
    s3 = make_odd((x - 2) * (x - 2))
    r3 = make_odd((x + 3) * (x + 3))
    # Return as [s1, r1] to match existing two-level shape
    return [float(s1), float(r1)]


