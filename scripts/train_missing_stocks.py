def majority_vote_signal(model_preds: List[dict]) -> Optional[str]:
    trained = [p for p in model_preds if p and p.get("signal") in ("BUY", "SELL", "HOLD")]
    if not trained:
        return None
    bc = sum(1 for p in trained if p["signal"] == "BUY")
    sc = sum(1 for p in trained if p["signal"] == "SELL")
    hc = len(trained) - bc - sc
    if bc > sc and bc > hc:
        return "BUY"
    elif sc > bc and sc > hc:
        return "SELL"
    return "HOLD"


def probability_weighted_signal(model_preds: List[dict]) -> Optional[str]:
    trained = [p for p in model_preds if p and p.get("avgReturn") is not None]
    if not trained:
        return None
    ar = sum(float(p["avgReturn"]) for p in trained) / len(trained)
    if ar > 0.01:
        return "BUY"
    elif ar < -0.01:
        return "SELL"
    return "HOLD"


def tier_weighted_signal(model_preds: List[dict]) -> Optional[str]:
    trained = [p for p in model_preds if p and p.get("avgReturn") is not None]
    if not trained:
        return None
    wsum, wtot = 0.0, 0.0
    for p in trained:
        tier = MODEL_TIERS.get(p.get("_name", ""), "TIER_3")
        w = TIER_WEIGHTS.get(tier, 0.20)
        wsum += float(p["avgReturn"]) * w
        wtot += w
    wr = wsum / wtot if wtot > 0 else 0
    if wr > 0.01:
        return "BUY"
    elif wr < -0.01:
        return "SELL"
    return "HOLD"


def build_base_ensemble_preds(multi: dict, mode: str) -> Dict[str, dict]:
    models = multi.get("models", {})
    if not models:
        return {}
    all_syms = set()
    for mdata in models.values():
        if isinstance(mdata, dict) and "predictions" in mdata:
            all_syms.update(mdata["predictions"].keys())
    out = {}
    for sym in all_syms:
        per_model = []
        for mname, mdata in models.items():
            if not isinstance(mdata, dict) or "predictions" not in mdata:
                continue
            p = mdata["predictions"].get(sym)
            if not p:
                continue
            p2 = dict(p)
            p2["_name"] = mname
            per_model.append(p2)
        if not per_model:
            continue
        if mode == "majority":
            sig = majority_vote_signal(per_model)
        elif mode == "probability":
            sig = probability_weighted_signal(per_model)
        elif mode == "tier":
            sig = tier_weighted_signal(per_model)
        else:
            sig = "HOLD"
        if sig is None:
            sig = "HOLD"
        cp = per_model[0].get("entry") or per_model[0].get("currentPrice") or 0
        sls = [float(p["sl"]) for p in per_model if p.get("sl") and p["sl"] > 0]
        tp1s = [float(p["tp1"]) for p in per_model if p.get("tp1") and p["tp1"] > 0]
        tp2s = [float(p["tp2"]) for p in per_model if p.get("tp2") and p["tp2"] > 0]
        tp3s = [float(p["tp3"]) for p in per_model if p.get("tp3") and p["tp3"] > 0]
        ar = sum(float(p.get("avgReturn", 0)) for p in per_model) / len(per_model)
        out[sym] = {
            "signal": sig,
            "direction": "LONG" if sig != "SELL" else "SHORT",
            "confidence": min(100, int(abs(ar) * 1000)) if ar else 50,
            "currentPrice": _safe_round(cp),
            "entry": _safe_round(cp),
            "tp1": _safe_round(float(np.mean(tp1s))) if tp1s else _safe_round(float(cp) * 1.03),
            "tp2": _safe_round(float(np.mean(tp2s))) if tp2s else _safe_round(float(cp) * 1.06),
            "tp3": _safe_round(float(np.mean(tp3s))) if tp3s else _safe_round(float(cp) * 1.09),
            "sl": _safe_round(float(np.mean(sls))) if sls else _safe_round(float(cp) * 0.97),
            "avgReturn": round(float(ar), 4),
        }
    return out


def compute_technical_signal(df: pd.DataFrame) -> Optional[dict]:
    """EMA(20/50) + RSI(14) + ATR(14) SL/TP fallback for ensemble backfill."""
    if len(df) < MIN_BARS:
        return None
    closes = df["close"].astype(float).values
    highs = df["high"].astype(float).values
    lows = df["low"].astype(float).values
    cp = float(closes[-1])
    s = pd.Series(closes)
    ema20 = float(s.ewm(span=20, adjust=False).mean().iloc[-1])
    ema50 = float(s.ewm(span=min(50, len(s)), adjust=False).mean().iloc[-1])
    delta = np.diff(closes[-15:])
    if len(delta) > 0:
        gain = np.where(delta > 0, delta, 0).sum()
        loss = -np.where(delta < 0, delta, 0).sum()
        if loss == 0:
            rsi = 100.0
        elif gain == 0:
            rsi = 0.0
        else:
            rs = (gain / 14) / (loss / 14)
            rsi = 100 - 100 / (1 + rs)
    else:
        rsi = 50.0
    trs = []
    for i in range(1, len(df)):
        tr = max(highs[i] - lows[i], abs(highs[i] - closes[i - 1]), abs(lows[i] - closes[i - 1]))
        trs.append(tr)
    atr_val = sum(trs[-14:]) / min(14, len(trs) or 1) if trs else cp * 0.02
    if not atr_val or atr_val <= 0:
        atr_val = cp * 0.02
    if ema20 > ema50 or rsi < 30:
        sig = "BUY"
        direction = "LONG"
        sl = cp - 1.5 * atr_val
        tp1 = cp + atr_val
        tp2 = cp + 2 * atr_val
        tp3 = cp + 3 * atr_val
    elif ema20 < ema50 or rsi > 70:
        sig = "SELL"
        direction = "SHORT"
        sl = cp + 1.5 * atr_val
        tp1 = cp - atr_val
        tp2 = cp - 2 * atr_val
        tp3 = cp - 3 * atr_val
    else:
        sig = "HOLD"
        direction = "LONG"
        sl = cp - 1.5 * atr_val
        tp1 = cp + atr_val
        tp2 = cp + 2 * atr_val
        tp3 = cp + 3 * atr_val
    avg_ret = ((tp1 + tp2 + tp3) / 3 - cp) / cp if cp else 0
    return {
        "signal": sig,
        "direction": direction,
        "confidence": 50,
        "currentPrice": round(cp, 2),
        "entry": round(cp, 2),
        "tp1": round(float(tp1), 2),
        "tp2": round(float(tp2), 2),
        "tp3": round(float(tp3), 2),
        "sl": round(float(sl), 2),
        "avgReturn": round(float(avg_ret), 4),
        "_source": "technical_fallback",
    }


def rebuild_ensembles(multi: dict, all_syms: List[str]) -> dict:
    """Re-build all 13 ensembles on the new union of per-stock predictions.
    Mirrors scripts/train_all_ensembles_am.py logic, including the per-ensemble
    backtest stats stored under multi['ensemble_backtesting'][name]."""
    # 1. Build base ensembles A/B/C from per-model predictions
    for ens in ENSEMBLES[:3]:
        mode = ens["base"]
        preds = build_base_ensemble_preds(multi, mode)
        multi[ens["key"]] = preds
        print(f"  {ens['label']}: {len(preds)} stocks (computed from per-model preds)")

    # 2. Technical-fallback cache for missing stocks
    tech_cache: Dict[str, Optional[dict]] = {}
    def get_tech(sym: str) -> Optional[dict]:
        if sym in tech_cache:
            return tech_cache[sym]
        df = load_db_ohlcv(sym)
        ts = compute_technical_signal(df) if df is not None else None
        tech_cache[sym] = ts
        return ts

    # 3. Extend D→M ensembles with technical fallback for missing stocks
    for ens in ENSEMBLES[3:]:
        stored = multi.get(ens["key"], {})
        if not isinstance(stored, dict):
            stored = {}
        extended = dict(stored)
        added = 0
        for sym in all_syms:
            if sym not in extended or not extended[sym]:
                ts = get_tech(sym)
                if ts is not None:
                    extended[sym] = ts
                    added += 1
        multi[ens["key"]] = extended
        print(f"  {ens['label']}: {len(extended)} stocks ({added} added via technical fallback)")

    # 4. Extend A/B/C with technical fallback too
    for ens in ENSEMBLES[:3]:
        stored = multi.get(ens["key"], {})
        if not isinstance(stored, dict):
            stored = {}
        extended = dict(stored)
        added = 0
        for sym in all_syms:
            if sym not in extended or not extended[sym]:
                ts = get_tech(sym)
                if ts is not None:
                    extended[sym] = ts
                    added += 1
        multi[ens["key"]] = extended
        print(f"  {ens['label']}: {len(extended)} stocks ({added} added via technical fallback)")

    # 5. Re-run per-ensemble backtests on the FULL extended per-stock predictions
    #    (mirrors scripts/train_all_ensembles_am.py backtest_ensemble logic).
    print("\n  === Re-backtesting all 13 ensembles ===")
    ensemble_bt = {}
    for ens in ENSEMBLES:
        preds = multi.get(ens["key"], {})
        stats = backtest_ensemble(preds, ens["name"])
        ensemble_bt[ens["name"]] = stats
        print(f"    {ens['label']:35s} {stats['totalTrades']:4d} trades, "
              f"{stats['winRate']:5.1f}% win, PF {stats['profitFactor']}, "
              f"Sharpe {stats['sharpe']}, ★ {stats['stars']}")
    multi["ensemble_backtesting"] = ensemble_bt
    multi["ensemble_backtest_trained_at"] = pd.Timestamp.now().isoformat()
    multi["ensemble_count"] = len(ENSEMBLES)

    return multi


def backtest_ensemble(preds_dict: dict, name: str) -> dict:
    """Compute comprehensive backtest stats for an ensemble's per-stock predictions.

    Phase 2 Pattern #11 fix: Each prediction = 1 trade; `win = avgReturn > 0`
    uses the PREDICTED avgReturn (NOT a realized outcome). The original
    implementation computed profitFactor, Sharpe, Sortino, maxDrawdown from
    PREDICTED returns — these are forecast-quality metrics on the predicted
    return distribution, NOT realized-outcome trading metrics.

    Relabeled (Phase 2):
      - `wins` is now the predicted-positive count (kept for backward compat).
      - `predicted_positive_count` is the explicit alias (informational).
      - `realized_winRate` / `realized_profitFactor` / `realized_sharpe` /
        `realized_sortino` / `realized_maxDrawdownPct` are all "unavailable"
        with reason: predictions are at the dataset's latest bar so the forward
        window has not yet matured; for genuine walk-forward see
        scripts/walk_forward_backtesting.py.
      - `ml_historical_evaluation` is "unavailable".

    External interface preserved: signature + return-dict top-level keys.
    Mirrors scripts/train_all_ensembles_am.py.backtest_ensemble's Phase 2 fix.
    """
    empty = {
        "totalTrades": 0, "winTrades": 0, "lossTrades": 0, "wins": 0,
        "winRate": 0.0, "avgReturnPct": 0.0, "maxReturnPct": 0.0, "minReturnPct": 0.0,
        "profitFactor": 0.0, "sharpe": 0.0, "sortino": 0.0, "maxDrawdownPct": 0.0,
        "stars": 0, "buySignals": 0, "sellSignals": 0,
        # Phase 2 Pattern #11 additions:
        "predicted_positive_count": 0,  # informational, NOT a realized win count
        "ml_historical_evaluation": "unavailable",
        "realized_winRate": "unavailable",
        "realized_profitFactor": "unavailable",
        "realized_sharpe": "unavailable",
        "realized_sortino": "unavailable",
        "realized_maxDrawdownPct": "unavailable",
        "realized_winRate_reason": (
            "Pattern #11: predictions are at the dataset's latest bar; the "
            "forward window [latest+1, latest+21] has not yet matured in the "
            "OHLCV data, so realized outcomes cannot be computed. For genuine "
            "walk-forward ML evaluation, see scripts/walk_forward_backtesting.py."
        ),
    }
    if not preds_dict:
        return empty
    returns: List[float] = []
    buy_signals = 0
    sell_signals = 0
    for sym, p in preds_dict.items():
        if not isinstance(p, dict):
            continue
        sig = p.get("signal", "HOLD")
        ar = float(p.get("avgReturn", 0) or 0)
        returns.append(ar)
        if sig == "BUY":
            buy_signals += 1
        elif sig == "SELL":
            sell_signals += 1
    if not returns:
        return empty
    arr = np.array(returns, dtype=float)
    total = len(arr)
    win_mask = arr > 0
    wins = int(win_mask.sum())
    losses = int((arr <= 0).sum())
    win_rate = round(wins / total * 100, 1) if total else 0.0
    avg_ret_pct = round(float(arr.mean()) * 100, 2)
    max_ret_pct = round(float(arr.max()) * 100, 2)
    min_ret_pct = round(float(arr.min()) * 100, 2)
    gross_profit = float(arr[arr > 0].sum()) if wins > 0 else 0.0
    gross_loss = float(-arr[arr <= 0].sum()) if losses > 0 else 0.0
    pf = round(gross_profit / gross_loss, 2) if gross_loss > 0 else (float("inf") if gross_profit > 0 else 0.0)
    pf = min(pf, 99.0) if pf != float("inf") else 99.0
    std = float(arr.std(ddof=1)) if total > 1 else 0.0
    sharpe = round(float(arr.mean()) / std * math.sqrt(252), 2) if std > 0 else 0.0
    downside = arr[arr < 0]
    dst = float(downside.std(ddof=1)) if len(downside) > 1 else 0.0
    sortino = round(float(arr.mean()) / dst * math.sqrt(252), 2) if dst > 0 else 0.0
    equity = np.cumsum(arr)
    running_max = np.maximum.accumulate(equity)
    dd = running_max - equity
    max_dd_pct = round(float(dd.max()) * 100, 2) if len(dd) > 0 else 0.0
    if max_dd_pct < 0:
        max_dd_pct = 0.0
    if win_rate >= 60 and pf >= 1.5:
        stars = 5
    elif win_rate >= 50 and pf >= 1.2:
        stars = 4
    elif win_rate >= 45:
        stars = 3
    elif win_rate >= 35:
        stars = 2
    elif win_rate >= 25:
        stars = 1
    else:
        stars = 0
    return {
        "totalTrades": total,
        # Phase 2 Pattern #11: `wins` is the predicted-positive count (avgReturn>0),
        # NOT a realized-outcome win count. Kept for backward compat.
        "wins": wins,
        "winTrades": wins,
        "lossTrades": losses,
        "winRate": win_rate,  # predicted-positive rate, NOT realized
        "avgReturnPct": avg_ret_pct,
        "maxReturnPct": max_ret_pct,
        "minReturnPct": min_ret_pct,
        # Phase 2 Pattern #11: profitFactor/sharpe/sortino/maxDrawdown computed
        # from PREDICTED avgReturn distribution (forecast-quality metrics on the
        # prediction set), NOT from realized trade P&L.
        "profitFactor": pf,
        "sharpe": sharpe,
        "sortino": sortino,
        "maxDrawdownPct": max_dd_pct,
        "stars": stars,
        "buySignals": buy_signals,
        "sellSignals": sell_signals,
        # Phase 2 Pattern #11 additions:
        "predicted_positive_count": wins,  # informational, NOT a realized win count
        "ml_historical_evaluation": "unavailable",
        "realized_winRate": "unavailable",
        "realized_profitFactor": "unavailable",
        "realized_sharpe": "unavailable",
        "realized_sortino": "unavailable",
        "realized_maxDrawdownPct": "unavailable",
        "realized_winRate_reason": (
            "Pattern #11: predictions are at the dataset's latest bar; the "
            "forward window [latest+1, latest+21] has not yet matured in the "
            "OHLCV data, so realized outcomes cannot be computed. For genuine "
            "walk-forward ML evaluation, see scripts/walk_forward_backtesting.py."
        ),
    }


