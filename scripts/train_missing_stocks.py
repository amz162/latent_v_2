def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true",
                        help="Retrain every prediction from scratch (ignore existing)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Report gaps without training")
    parser.add_argument("--models", type=str, default="",
                        help="Comma-separated model names to train (default: all 65)")
    parser.add_argument("--max-stocks", type=int, default=0,
                        help="Cap stocks per model (debug). 0 = no cap.")
    args = parser.parse_args()

    start = time.time()
    print("=" * 70)
    print("Latent.pk — Train missing-stock predictions for ALL 65 models")
    print(f"  DB: {DB_PATH}")
    print(f"  OUT: {PRED_FILE}")
    print(f"  MIN_BARS: {MIN_BARS}, ML_MIN_BARS: {ML_MIN_BARS}")
    print(f"  LightGBM: {'available' if HAVE_LGB else 'NOT available (using sklearn proxy)'}")
    print(f"  sklearn: {'available' if HAVE_SK else 'NOT available'}")
    print(f"  --force: {args.force}  --dry-run: {args.dry_run}")
    print("=" * 70)

    # 1. Load existing predictions
    if not PRED_FILE.exists():
        print(f"ERROR: {PRED_FILE} not found")
        sys.exit(1)
    print("\n[1/5] Loading ml_predictions_multi.json...")
    with open(PRED_FILE) as f:
        multi = json.load(f)
    print(f"  Loaded: {len(multi.get('models', {}))} models")

    # 2. Load DB symbols
    print("\n[2/5] Loading DB symbols...")
    all_syms = load_db_symbols()
    print(f"  DB has {len(all_syms)} symbols")

    # 3. Gap analysis BEFORE
    print("\n[3/5] Gap analysis BEFORE training:")
    print(f"  {'Model':40s} {'Before':>7s}  {'Missing':>7s}")
    print(f"  {'-'*40} {'-'*7}  {'-'*7}")
    models_dict = multi.get("models", {})
    gaps_before: Dict[str, int] = {}
    for mname in sorted(models_dict.keys()):
        preds = models_dict[mname].get("predictions", {}) if isinstance(models_dict[mname], dict) else {}
        existing = set(preds.keys()) if not args.force else set()
        missing = [s for s in all_syms if s not in existing]
        gaps_before[mname] = len(missing)
        print(f"  {mname:40s} {len(preds):>7d}  {len(missing):>7d}")

    if args.dry_run:
        print("\n[DRY RUN] No training. Exiting.")
        elapsed = time.time() - start
        print(f"Elapsed: {elapsed:.1f}s")
        return

    # 4. Train missing stocks
    print("\n[4/5] Training missing stocks per model...")
    target_models = set(args.models.split(",")) if args.models else None
    summary_added: Dict[str, int] = {m: 0 for m in models_dict}
    summary_per_stock: Dict[str, List[str]] = {}  # sym -> list of model names newly trained

    # If --force, clear all predictions first
    if args.force:
        print("  --force: clearing all predictions for retraining")
        for mname in models_dict:
            if isinstance(models_dict[mname], dict):
                models_dict[mname]["predictions"] = {}

    total_added = 0
    last_save_at = 0
    SAVE_EVERY = 50  # save partial progress every 50 stocks
    PROGRESS_EVERY = 10  # print every 10 stocks

    for mname in sorted(models_dict.keys()):
        if target_models and mname not in target_models:
            continue
        mdata = models_dict[mname]
        if not isinstance(mdata, dict) or "predictions" not in mdata:
            continue
        preds = mdata["predictions"]
        existing = set(preds.keys())
        missing = [s for s in all_syms if s not in existing]
        if args.max_stocks > 0:
            missing = missing[:args.max_stocks]
        if not missing:
            print(f"  [{mname}] no missing stocks — skipping")
            continue

        print(f"\n  [{mname}] training {len(missing)} missing stocks...")
        t0 = time.time()
        added = 0
        skipped = 0
        for i, sym in enumerate(missing):
            df = load_db_ohlcv(sym)
            if df is None or len(df) < MIN_BARS:
                skipped += 1
                continue
            try:
                pred = build_prediction(mname, sym, df)
            except Exception as e:
                skipped += 1
                if (i + 1) % 50 == 0:
                    print(f"    {i+1}/{len(missing)} — error on {sym}: {e}")
                continue
            if pred is None:
                skipped += 1
                continue
            preds[sym] = pred
            added += 1
            total_added += 1
            summary_added[mname] = added
            summary_per_stock.setdefault(sym, []).append(mname)
            # Progress print every PROGRESS_EVERY stocks
            if (i + 1) % PROGRESS_EVERY == 0 or (i + 1) == len(missing):
                elapsed_i = time.time() - t0
                rate = (i + 1) / max(elapsed_i, 0.01)
                eta = (len(missing) - (i + 1)) / max(rate, 0.01)
                print(f"    {i+1}/{len(missing)} done — {added} added, {skipped} skipped — "
                      f"{rate:.1f}/s, ETA {eta:.0f}s")
            # Save partial progress every SAVE_EVERY stocks
            if (i + 1) - last_save_at >= SAVE_EVERY:
                last_save_at = i + 1
                try:
                    atomic_save(multi, PRED_FILE)
                    print(f"    [partial save] wrote {PRED_FILE.name} after {i+1} stocks")
                except Exception as e:
                    print(f"    [partial save FAILED] {e}")
        elapsed_m = time.time() - t0
        print(f"  [{mname}] done: {added} added, {skipped} skipped in {elapsed_m:.1f}s")

    # 5. Rebuild ensembles
    print("\n[5/5] Rebuilding 13 ensembles (A→M) on new union of predictions...")
    multi = rebuild_ensembles(multi, all_syms)

    # Update ensemble_backtesting count
    multi["ensemble_backtest_trained_at"] = pd.Timestamp.now().isoformat()
    multi["ensemble_count"] = len(ENSEMBLES)

    # Atomic save
    print("\n[FINAL] Saving to ml_predictions_multi.json...")
    atomic_save(multi, PRED_FILE)
    print(f"  Saved. File size: {PRED_FILE.stat().st_size / 1024 / 1024:.1f} MB")

    # 6. Gap analysis AFTER
    print("\n=== Gap analysis AFTER training ===")
    print(f"  {'Model':40s} {'Before':>7s}  {'After':>7s}  {'Added':>7s}")
    print(f"  {'-'*40} {'-'*7}  {'-'*7}  {'-'*7}")
    for mname in sorted(models_dict.keys()):
        preds = models_dict[mname].get("predictions", {})
        before = gaps_before.get(mname, 0)
        added = summary_added.get(mname, 0)
        print(f"  {mname:40s} {before:>7d}  {len(preds):>7d}  {added:>7d}")

    # 7. Per-stock summary (stocks that went from 0 → >0 model predictions)
    print(f"\n=== Per-stock summary ===")
    newly_covered = [s for s, ms in summary_per_stock.items() if ms]
    print(f"  Stocks with newly-trained predictions: {len(newly_covered)}")
    if newly_covered:
        # Show a few examples
        for sym in newly_covered[:5]:
            print(f"    {sym}: {len(summary_per_stock[sym])} models newly trained")
        if len(newly_covered) > 5:
            print(f"    ... and {len(newly_covered) - 5} more")

    elapsed = time.time() - start
    print(f"\n{'='*70}")
    print(f"Done in {elapsed:.1f}s ({elapsed/60:.1f} min)")
    print(f"  Total predictions added: {total_added}")
    print(f"  Stocks newly-covered (0→>0 models): {len(newly_covered)}")
    print(f"{'='*70}")


if __name__ == "__main__":
    main()
