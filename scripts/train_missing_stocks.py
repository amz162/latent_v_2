_OHLCV_CACHE: Dict[str, pd.DataFrame] = {}


def load_db_ohlcv(symbol: str) -> Optional[pd.DataFrame]:
    if symbol in _OHLCV_CACHE:
        return _OHLCV_CACHE[symbol]
    conn = get_conn()
    try:
        df = pd.read_sql(
            "SELECT date, open, high, low, close, volume FROM OhlcvBar WHERE symbol=? ORDER BY date ASC",
            conn, params=(symbol,),
        )
    except Exception:
        return None
    if df.empty:
        _OHLCV_CACHE[symbol] = None
        return None
    # Keep only rows where close>0 (drop the all-zero listings). We don't
    # strictly require volume>0 — many PSX stocks have close prices even
    # when volume is recorded as 0 (illiquid days), and the technical
    # indicators (RSI/MACD/ATR) only need price data.
    df = df[df["close"] > 0].reset_index(drop=True)
    # If close>0 but open/high/low are 0, fill them with close (proxy OHLCV)
    for col in ["open", "high", "low"]:
        df.loc[df[col] <= 0, col] = df.loc[df[col] <= 0, "close"]
    # Volume: replace 0 with 1 (so volume_sma_20_ratio doesn't blow up).
    # This is a coarse proxy but the user explicitly said "train on less
    # data" so we use whatever is available.
    df.loc[df["volume"] <= 0, "volume"] = 1.0
    if df.empty:
        _OHLCV_CACHE[symbol] = None
        return None
    _OHLCV_CACHE[symbol] = df
    return df


